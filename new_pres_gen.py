def kpi(slide, l, t, w, h, label, value, sub="", lc=None, vc=None):
    lc = lc or C["blue"]; vc = vc or C["navy"]
    rrect(slide, l, t, w, h, C["cardbg"], C["border"], 0.75)
    box = slide.shapes.add_textbox(l+IN(0.15), t+IN(0.12), w-IN(0.3), h-IN(0.18))
    tf  = box.text_frame; tf.word_wrap = True
    add_paras(tf, [
        (label.upper(), 8, True,  lc,     1),
        (value,         18,True,  vc,     2),
        (sub,           8.5,False,C["slate"], 0),
    ])


def bullet_card(slide, l, t, w, h, title, bullets,
                tc=None, bc=None, ts=11, bs=9.5, bg=None, accent=None):
    tc  = tc  or C["navy"]
    bc  = bc  or C["slate"]
    bg  = bg  or C["cardbg"]
    rrect(slide, l, t, w, h, bg, C["border"], 0.75)
    if accent:
        rrect(slide, l, t, IN(0.07), h, accent)  # left accent bar
    box = slide.shapes.add_textbox(l+IN(0.2), t+IN(0.14), w-IN(0.3), h-IN(0.22))
    tf  = box.text_frame; tf.word_wrap = True
    p0  = tf.paragraphs[0]
    p0.text = title; p0.font.size = Pt(ts)
    p0.font.bold = True; p0.font.color.rgb = tc
    p0.space_after = Pt(4)
    for b in bullets:
        px = tf.add_paragraph()
        px.text = f"\u2022  {b}"
        px.font.size = Pt(bs); px.font.color.rgb = bc
        px.space_after = Pt(3)


