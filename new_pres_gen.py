def rect(slide, l, t, w, h, fill, border=None, bpt=0):
    sh = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, l, t, w, h)
    sh.fill.solid(); sh.fill.fore_color.rgb = fill
    if border and bpt:
        sh.line.color.rgb = border; sh.line.width = Pt(bpt)
    else:
        sh.line.fill.background()
    return sh


def rrect(slide, l, t, w, h, fill, border=None, bpt=1):
    sh = slide.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, l, t, w, h)
    sh.fill.solid(); sh.fill.fore_color.rgb = fill
    if border:
        sh.line.color.rgb = border; sh.line.width = Pt(bpt)
    else:
        sh.line.fill.background()
    return sh


def tb(slide, text, l, t, w, h, size=10, bold=False, color=None,
        align=PP_ALIGN.LEFT, wrap=True, italic=False):
    box = slide.shapes.add_textbox(l, t, w, h)
    tf  = box.text_frame; tf.word_wrap = wrap
    p   = tf.paragraphs[0]
    p.text = text; p.alignment = align
    p.font.size = Pt(size); p.font.bold = bold; p.font.italic = italic
    if color: p.font.color.rgb = color
    return box


def img(slide, path, l, t, w, h):
    if os.path.exists(path):
        slide.shapes.add_picture(path, l, t, w, h)
    else:
        rrect(slide, l, t, w, h, C["cardbg"], C["border"])
        tb(slide, f"[Missing: {os.path.basename(path)}]",
           l+IN(0.1), t+h/2-IN(0.2), w-IN(0.2), IN(0.4),
           size=8, color=C["slate"], align=PP_ALIGN.CENTER)


def add_paras(tf, items):
    """items = list of (text, size, bold, color, space_after)"""
    for i, (text, size, bold, color, safter) in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = text
        p.font.size = Pt(size); p.font.bold = bold
        p.font.color.rgb = color
        p.space_after = Pt(safter)


